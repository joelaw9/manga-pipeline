-- Schema step 0076 (SPEC "Junk decisions", decisions and decision commands): junk decisions keep their history.
-- A decision is active, superseded by a newer imported decision on its key (superseded_by), or retired by an act of
-- junk redecide or junk undo (retired_by); only active decisions decide, and none is deleted. An act is 1 junk redecide
-- or junk undo (undoes: the act it reverses, once); junk_act_row logs every decision an act wrote, retired or restored.
-- images: the candidate folder of a decision made from a candidate (its images, kept with it).
CREATE TABLE junk_act (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    command TEXT NOT NULL,
    at TEXT NOT NULL,
    undoes BIGINT UNIQUE REFERENCES junk_act (id)
);

ALTER TABLE junk_decision ADD COLUMN superseded_by BIGINT REFERENCES junk_decision (id);
ALTER TABLE junk_decision ADD COLUMN written_by BIGINT REFERENCES junk_act (id);
ALTER TABLE junk_decision ADD COLUMN retired_by BIGINT REFERENCES junk_act (id);
ALTER TABLE junk_decision ADD COLUMN images TEXT;

-- 1 active decision per series key, kind and key; inactive ones are history.
DROP INDEX junk_decision_unit;
CREATE UNIQUE INDEX junk_decision_unit ON junk_decision (series_key, kind, md5(key))
    WHERE superseded_by IS NULL AND retired_by IS NULL;

CREATE TABLE junk_act_row (
    act BIGINT NOT NULL REFERENCES junk_act (id),
    decision BIGINT NOT NULL REFERENCES junk_decision (id),
    change TEXT NOT NULL CHECK (change IN ('wrote', 'retired', 'restored')),
    PRIMARY KEY (act, decision, change)
);
