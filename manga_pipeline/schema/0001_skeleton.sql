-- Schema step 0001 (SPEC "State"): the step record, meta, and the tables the skeleton and its parts work on.
-- Times are ISO 8601 UTC text. JSON columns are text checked by IS JSON.

CREATE TABLE schema_step (
    name TEXT PRIMARY KEY,
    applied_at TEXT NOT NULL
);

CREATE TABLE meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

INSERT INTO meta (key, value) VALUES ('database_id', replace(gen_random_uuid()::text, '-', ''));

CREATE TABLE series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    kavita_series_id BIGINT UNIQUE,
    kavita_library_id BIGINT,
    folder TEXT,
    origin TEXT NOT NULL CHECK (origin IN ('kavita', 'new')),
    status TEXT NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'needs_human')),
    status_reason TEXT
);

CREATE TABLE published_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_path TEXT NOT NULL UNIQUE,
    series_id BIGINT NOT NULL REFERENCES series (id),
    identity TEXT NOT NULL,
    source TEXT,
    parse_fields TEXT CHECK (parse_fields IS NULL OR parse_fields IS JSON),
    state TEXT NOT NULL CHECK (state IN ('unconfirmed', 'confirmed')),
    size BIGINT,
    median_page_width BIGINT,
    strip_length BIGINT,
    page_phashes TEXT CHECK (page_phashes IS NULL OR page_phashes IS JSON),
    pages_in BIGINT,
    pages_out BIGINT,
    comicinfo_series TEXT,
    comicinfo_volume TEXT,
    comicinfo_number TEXT,
    comicinfo_title TEXT,
    comicinfo_date TEXT,
    origin TEXT NOT NULL CHECK (origin IN ('pipeline', 'bulk'))
);

-- An identity is never reused: an id names files on the share and is kept in other tables, so it stays unique even
-- after state reset empties the table.
CREATE TABLE chapter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id BIGINT NOT NULL REFERENCES series (id),
    kind TEXT NOT NULL CHECK (kind IN ('download', 'rewrite')),
    identity TEXT NOT NULL,
    download_path TEXT,
    suwayomi_chapter_id BIGINT,
    source TEXT,
    stage TEXT NOT NULL
        CHECK (stage IN ('discover', 'validate', 'junk', 'convert', 'comicinfo', 'publish', 'confirm')),
    status TEXT NOT NULL CHECK (status IN ('ready', 'claimed', 'waiting', 'needs_human', 'done')),
    waiting_on TEXT
        CHECK (waiting_on IN ('suwayomi_download', 'bulk_conversion', 'junk_decision', 'kavita_scan')),
    wait_data TEXT CHECK (wait_data IS NULL OR wait_data IS JSON),
    attempts BIGINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error TEXT,
    claimed_by TEXT,
    staged_path TEXT,
    staged_size BIGINT,
    library_path TEXT,
    published_file_id BIGINT REFERENCES published_file (id),
    comicinfo_series TEXT,
    comicinfo_volume TEXT,
    comicinfo_number TEXT,
    comicinfo_title TEXT,
    comicinfo_date TEXT,
    convert_result TEXT,
    output_pages TEXT CHECK (output_pages IS NULL OR output_pages IS JSON),
    discovered_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    CHECK ((status = 'waiting') = (waiting_on IS NOT NULL)),
    CHECK ((status = 'claimed') = (claimed_by IS NOT NULL))
);

-- At most 1 open chapter per published file (a rewrite, or a better copy replacing it).
CREATE UNIQUE INDEX chapter_open_per_published_file ON chapter (published_file_id)
    WHERE published_file_id IS NOT NULL AND status != 'done';

CREATE TABLE page (
    chapter_id BIGINT NOT NULL REFERENCES chapter (id) ON DELETE CASCADE,
    page_index BIGINT NOT NULL,
    name TEXT NOT NULL,
    bytes BIGINT,
    sha1 TEXT,
    width BIGINT,
    height BIGINT,
    format TEXT,
    blank BIGINT CHECK (blank IN (0, 1)),
    phash TEXT,
    junk_signature TEXT,
    colour_class TEXT,
    chroma DOUBLE PRECISION,
    PRIMARY KEY (chapter_id, page_index)
);

CREATE TABLE handled_chapter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id BIGINT NOT NULL REFERENCES series (id),
    identity TEXT NOT NULL,
    outcome TEXT NOT NULL CHECK (outcome IN ('published', 'rejected', 'duplicate', 'dropped')),
    content_digest TEXT,
    handled_at TEXT NOT NULL
);

CREATE INDEX handled_chapter_series_identity ON handled_chapter (series_id, identity);
